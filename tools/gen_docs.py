#!/usr/bin/env python3
"""Regenerate docs/modules.md from the module registry (the single source of truth).

    python tools/gen_docs.py          # write docs/modules.md
    python tools/gen_docs.py --check  # exit 1 if docs/modules.md is out of date (used in CI)
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

from basilisk_mcp.registry import DERIVED_VARIABLES, MESSAGE_TYPES, MODULE_TYPES, ORBIT_FIELDS

OUT = Path(__file__).resolve().parents[1] / "docs" / "modules.md"


def fmt(value) -> str:
    if value is None or value == []:
        return ""
    return f"`{value}`"


def render() -> str:
    lines = [
        "# Module catalog",
        "",
        "<!-- Generated by tools/gen_docs.py from src/basilisk_mcp/registry.py. Do not edit by hand. -->",
        "",
        "Every module type the server can place in a session. Parameters use SI units; the unit is part of "
        "the name. `ref` parameters name another module in the same session. Ports are connected with "
        "`connect(session_id, \"<module>.<output>\", \"<module>.<input>\")`; both ends must carry the same "
        "message type.",
        "",
        "| Type | Category | Basilisk class | Summary |",
        "|---|---|---|---|",
    ]
    for mt in MODULE_TYPES.values():
        lines.append(f"| [`{mt.name}`](#{mt.name.replace('_', '-')}) | {mt.category} | `{mt.basilisk_class}` | {mt.summary} |")
    for mt in MODULE_TYPES.values():
        lines += ["", f"## {mt.name.replace('_', '-')}", "", mt.description, "",
                  f"Category: **{mt.category}** task · Basilisk: `{mt.basilisk_class}`", ""]
        if mt.params:
            lines += ["| Parameter | Kind | Unit | Default | Constraints | Description |", "|---|---|---|---|---|---|"]
            for name, p in mt.params.items():
                cons = []
                if p.required:
                    cons.append("required")
                if p.nullable:
                    cons.append("optional")
                if p.minimum is not None:
                    cons.append(f"{'>' if p.exclusive_minimum else '>='} {p.minimum:g}")
                if p.maximum is not None:
                    cons.append(f"<= {p.maximum:g}")
                if p.choices:
                    cons.append("one of " + ", ".join(f"`{c}`" for c in p.choices))
                if p.ref_type:
                    cons.append(f"names a `{p.ref_type}`")
                if p.max_items is not None:
                    cons.append(f"{p.min_items or 0}..{p.max_items} items")
                lines.append(f"| `{name}` | {p.kind} | {p.unit} | {fmt(p.default)} | {'; '.join(cons)} | {p.description} |")
        else:
            lines.append("No parameters.")
        if mt.inputs:
            lines += ["", "**Inputs**", ""]
            lines += [f"* `{mt.name}.{k}` ← `{p.msg_type}`{' (required)' if p.required else ''}: {p.description}"
                      for k, p in mt.inputs.items()]
        if mt.outputs:
            lines += ["", "**Outputs**", ""]
            lines += [f"* `{mt.name}.{k}` → `{p.msg_type}`: {p.description}" for k, p in mt.outputs.items()]
        if mt.name == "spacecraft":
            lines += ["", "**`orbit` fields** (classical elements relative to the attached gravity body)", "",
                      "| Field | Unit | Default | Description |", "|---|---|---|---|"]
            lines += [f"| `{k}` | {p.unit} | {fmt(p.default)} | {p.description} |" for k, p in ORBIT_FIELDS.items()]
    lines += ["", "## Recordable variables", "",
              "Raw variables come from the Basilisk message. Derived variables are computed by the server and "
              "can be used in `query_results`, `plot_results` and `compare_runs`.", "",
              "| Message type | Variable | Unit | Derived | Description |", "|---|---|---|---|---|"]
    for msg, variables in MESSAGE_TYPES.items():
        for name, v in variables.items():
            lines.append(f"| `{msg}` | `{name}` | {v.unit} | | {v.description} |")
        for name, v in DERIVED_VARIABLES.get(msg, {}).items():
            lines.append(f"| `{msg}` | `{name}` | {v.unit} | yes | {v.description} |")
    return "\n".join(lines) + "\n"


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    text = render()
    if args.check:
        if not OUT.is_file() or OUT.read_text(encoding="utf-8") != text:
            print("docs/modules.md is out of date; run python tools/gen_docs.py", file=sys.stderr)
            sys.exit(1)
        return
    OUT.write_text(text, encoding="utf-8")
    print(f"Wrote {OUT}")


if __name__ == "__main__":
    main()
